"""Build BubbleMap's map overlay table: BubbleMap/Data/Overlays.lua.

Every zone's explored-area overlays (the painted land pieces the world map adds as you discover a
zone), explored or not, so BubbleMap can draw its "Map art" style fully revealed. The game's API only
returns the ones you've explored (C_MapExplorationInfo.GetExploredMapTextures); the full set is in the
game data. Design: docs/design/questmarker-map.md ("Map style").

From wago.tools at the build pinned in tools/toolchain.json (as tools/terrain.py):
  - UiMap.csv: zones (Type 3);
  - UiMapXMapArt.csv: each UI map's art (UiMapArtID; phase 0 only);
  - WorldMapOverlay.csv: an art's overlays: size (TextureWidth/Height), place (OffsetX/Y, in the art's
    pixels), Flags;
  - WorldMapOverlayTile.csv: an overlay's files by RowIndex/ColIndex (layer 0).
The same fields GetExploredMapTextures returns (textureWidth, textureHeight, offsetX, offsetY,
fileDataIDs row by row), so Art.lua draws them the same way.

Flags: 4 on about half the overlays, 0 on the rest; not documented. [Inferred] not the mouse-over-only
kind (classic zones have none of those), so every overlay is drawn; kept in the table to revisit.

Usage:
  python tools/overlays.py           fetch (cached in .tools/terrain/<build>/) and write the table
  python tools/overlays.py --check   only check the committed table is the one this build gives
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import terrain  # noqa: E402  (shared fetch/cache/table helpers)

ROOT = terrain.ROOT
OUT = ROOT / "BubbleMap" / "Data" / "Overlays.lua"
ZONE = "3"

# A known zone, as a check (Elwynn Forest has overlays: Goldshire, Northshire, ...).
SANITY = [(1429, "Elwynn Forest")]


def build_table(build: str) -> str:
  zones = {row["ID"]: row["Name_lang"] for row in terrain.table(build, "UiMap") if row["Type"] == ZONE}
  art_of = {}
  for row in terrain.table(build, "UiMapXMapArt"):
    if row["PhaseID"] == "0" and row["UiMapID"] in zones:
      art_of[row["UiMapID"]] = row["UiMapArtID"]
  tiles = defaultdict(dict)  # overlay ID -> {(row, col): file}
  for row in terrain.table(build, "WorldMapOverlayTile"):
    if row["LayerIndex"] == "0":
      tiles[row["WorldMapOverlayID"]][(int(row["RowIndex"]), int(row["ColIndex"]))] = int(row["FileDataID"])
  overlays = defaultdict(list)  # art ID -> overlays
  for row in terrain.table(build, "WorldMapOverlay"):
    files = tiles.get(row["ID"])
    if not files:
      continue
    rows = max(r for r, _ in files) + 1
    cols = max(c for _, c in files) + 1
    overlays[row["UiMapArtID"]].append({
      "id": int(row["ID"]), "w": int(row["TextureWidth"]), "h": int(row["TextureHeight"]),
      "x": int(row["OffsetX"]), "y": int(row["OffsetY"]), "flags": int(row["Flags"]), "cols": cols,
      "files": [files.get((r, c), 0) for r in range(rows) for c in range(cols)],
    })
  by_map = {}
  for ui_map, art in art_of.items():
    if overlays.get(art):
      by_map[int(ui_map)] = sorted(overlays[art], key=lambda o: o["id"])
  for ui_map, name in SANITY:
    if ui_map not in by_map:
      raise SystemExit(f"overlays: sanity check failed: no overlays for {name} ({ui_map})")

  lines = [
    "local _, ns = ...",
    "",
    "-- Generated by tools/overlays.py; don't edit. Every zone's world map overlays, explored or not:",
    "-- [UI map ID] = { { w, h, x, y (the art's pixels), cols (files per row), flags, files (row by row,",
    "-- FileDataIDs) }, ... }, as C_MapExplorationInfo.GetExploredMapTextures gives the explored ones.",
    "-- Source: wago.tools at the build below (UiMap, UiMapXMapArt, WorldMapOverlay, WorldMapOverlayTile).",
    "",
    "ns.Overlays = {",
    f'  build = "{build}",',
    "  maps = {",
  ]
  count = 0
  for ui_map in sorted(by_map):
    lines.append(f"    [{ui_map}] = {{  -- {zones[str(ui_map)]}")
    for o in by_map[ui_map]:
      files = ",".join(str(f) for f in o["files"])
      lines.append(f"      {{ w={o['w']}, h={o['h']}, x={o['x']}, y={o['y']}, cols={o['cols']}, "
                   f"flags={o['flags']}, files={{{files}}} }},")
      count += 1
    lines.append("    },")
  lines += ["  },", "}", ""]
  print(f"overlays: {len(by_map)} zones, {count} overlays")
  return "\n".join(lines)


def main() -> int:
  build = json.loads(terrain.TOOLCHAIN.read_text(encoding="utf-8"))["wow_ui_source"]["build"]
  text = build_table(build)
  if "--check" in sys.argv[1:]:
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current != text:
      print(f"overlays --check: {OUT.relative_to(ROOT)} is not the table for build {build}; run tools/overlays.py")
      return 1
    print(f"overlays --check: OK (build {build})")
    return 0
  OUT.write_text(text, encoding="utf-8", newline="\n")
  print(f"overlays: wrote {OUT.relative_to(ROOT)} ({len(text) / 1024:.0f} KB, build {build})")
  return 0


if __name__ == "__main__":
  sys.exit(main())
