"""Extract Questie's quest blacklist, evaluated for Forever, into Data/QuestieHidden.lua.

Questie hides quests that aren't in the game, duplicates, other versions' quests, and quests it
shouldn't draw on the map (started by reading a book, legacy rewards): a list in its own code
(Database/Corrections/QuestieQuestBlacklist.lua), not in the QuestieDB data BubbleQuest reads. This
reads that file from the player's Questie install and evaluates each entry the way Questie does on
Forever (Questie/Modules/Expansions.lua:21-23: Forever counts as Era, the lowest expansion; not SoD,
not Titan-Reforged, not the China region). Also its Scourge Invasion and AQ War Effort lists
(events not running).

Questie is GPLv3 (with the Questie team's consent for forks and copies, its LICENSE.md); so is
BubbleQuest. The output keeps the attribution. Re-run when Questie updates its list.

Usage: python tools/extract_questie_hidden.py [path to Questie's QuestieQuestBlacklist.lua]
"""
import re
import sys
from pathlib import Path

DEFAULT_SOURCE = Path(
  r"C:\Program Files (x86)\World of Warcraft\_forever_\Interface\AddOns\Questie\Database\Corrections"
  r"\QuestieQuestBlacklist.lua"
)
OUT = Path(__file__).resolve().parent.parent / "Data" / "QuestieHidden.lua"
EVENTS_OUT = Path(__file__).resolve().parent.parent / "Data" / "QuestieEvents.lua"

# Holiday quests (Questie's Database/Corrections/Holidays/quests/*.lua): which event each belongs to.
# Questie's blacklist hides them all; it shows an event's quests while the event runs.
EVENT_ENTRY = re.compile(r'^\s*tinsert\(eventQuests,\s*\{"([^"]+)",\s*(\d+)(.*)\}\)')

ENTRY = re.compile(r"^\s*\[(\d+)\]\s*=\s*(.+?),?\s*(--.*)?$")

# Questie's names, as Forever has them. Expansion order: Era < TBC < Wrath < Cata < MoP.
NAMES = {
  "Expansions.Current": "0", "Expansions.Era": "0", "Expansions.Tbc": "1", "Expansions.Wotlk": "2",
  "Expansions.Cata": "3", "Expansions.MoP": "4", "ContentPhases.activePhases.TBC": "0",
  "Questie.IsSoD": "False", "Questie.IsTitanReforged": "False", "Questie.IsChinaRegion": "False",
  "Questie.IsEURegion": "False", "Questie.IsClassic": "True", "Questie.IsTBC": "False",
  "HIDE_ON_MAP": "'map'", "true": "True", "false": "False", "~=": "!=",
}


def evaluate(expression: str):
  """True (hidden), 'map' (hidden on the map only) or False, as Questie evaluates it on Forever."""
  python = expression
  for name in sorted(NAMES, key=len, reverse=True):
    python = python.replace(name, NAMES[name])
  if re.search(r"[A-Za-z_]+\.", python):
    raise ValueError(f"unknown name in {expression!r}")
  return eval(python, {"__builtins__": {}}, {})  # only literals, numbers and and/or/not are left


def block(lines, start_pattern):
  """Lines of the table opened by the first line matching start_pattern, up to its closing brace."""
  inside, out = False, []
  for line in lines:
    if not inside and re.search(start_pattern, line):
      inside = True
      continue
    if inside:
      if re.match(r"^\s*}\s*$", line):
        break
      out.append(line)
  return out


def main() -> None:
  source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
  lines = source.read_text(encoding="utf-8").splitlines()
  hidden, map_only, skipped = {}, {}, 0
  for line in block(lines, r"local questsToBlacklist = \{"):
    m = ENTRY.match(line)
    if not m:
      continue
    quest_id, expression, comment = int(m.group(1)), m.group(2).strip(), (m.group(3) or "")
    value = evaluate(expression)
    note = comment.lstrip("-").strip()
    if value == "map":
      map_only[quest_id] = note
    elif value:
      hidden[quest_id] = note
    else:
      skipped += 1
  for name, why in (("InvasionQuests", "Scourge Invasion"), ("AQWarEffortQuests", "AQ War Effort")):
    for line in block(lines, rf"QuestieQuestBlacklist\.{name} = \{{"):
      m = ENTRY.match(line)
      if m:
        hidden.setdefault(int(m.group(1)), why)

  out = [
    "local ADDON_NAME, ns = ...",
    "",
    "-- GENERATED by tools/extract_questie_hidden.py from Questie's",
    "-- Database/Corrections/QuestieQuestBlacklist.lua, evaluated for Forever. Do not edit; re-run it.",
    "-- Questie (https://github.com/Questie/Questie) is GPLv3; its blacklist is the Questie team's work.",
    "-- 1: hidden (not in the game, duplicate, another version, event not running); 2: hidden on the map",
    "-- only (real, but not started from a place: a book, a legacy reward).",
    "",
    "ns.QuestieHidden = {",
  ]
  for quest_id in sorted(set(hidden) | set(map_only)):
    kind = 2 if quest_id in map_only and quest_id not in hidden else 1
    out.append(f"  [{quest_id}] = {kind},")
  out.append("}")
  OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
  print(f"wrote {OUT.name}: {len(hidden)} hidden, {len(map_only)} map-only ({skipped} entries not hidden on Forever)")
  write_events(source.parent / "Holidays" / "quests")


def write_events(folder: Path) -> None:
  """Each holiday quest's event, unless Questie hides it on Forever (its 7th field, evaluated)."""
  events = {}
  for path in sorted(folder.glob("*.lua")):
    for line in path.read_text(encoding="utf-8").splitlines():
      m = EVENT_ENTRY.match(line)  # commented-out lines start with "--" and don't match
      if not m:
        continue
      name, quest_id, rest = m.group(1), int(m.group(2)), m.group(3)
      fields = [f.strip() for f in rest.split(",")][1:] if rest.strip() else []
      hide = fields[5] if len(fields) >= 6 else "nil"
      if hide != "nil" and evaluate(hide):
        continue
      events[quest_id] = name
  out = [
    "local ADDON_NAME, ns = ...",
    "",
    "-- GENERATED by tools/extract_questie_hidden.py from Questie's Database/Corrections/Holidays/quests/.",
    "-- Do not edit; re-run it. Questie (https://github.com/Questie/Questie) is GPLv3.",
    "-- Each holiday quest's event, as Questie names it; shown while that event runs (Quests/Holidays.lua).",
    "",
    "ns.QuestieEvents = {",
  ]
  for quest_id in sorted(events):
    out.append(f'  [{quest_id}] = "{events[quest_id]}",')
  out.append("}")
  EVENTS_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
  names = sorted(set(events.values()))
  print(f"wrote {EVENTS_OUT.name}: {len(events)} quests in {len(names)} events: {', '.join(names)}")


if __name__ == "__main__":
  main()
