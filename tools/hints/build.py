"""Build Data/Hints.lua and docs/hints-review.md from the triage decisions.

  python tools/hints/build.py

Reads tools/hints/candidates.jsonl (from extract.py) and tools/hints/triage/*.jsonl (the triage pass,
see TRIAGE.md). Validates every decision, refuses to write on any problem, then generates:
  - Data/Hints.lua: ns.HintData[questID] = { hints = { { text, source } }, objectives = { [name] = { text, source } } }
  - docs/hints-review.md: every hint and do line next to its source text (the human review queue)
To correct a decision, edit its line in the triage file and rebuild.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CANDIDATES = HERE / "candidates.jsonl"
TRIAGE = HERE / "triage"
OUT_LUA = ROOT / "Data" / "Hints.lua"
OUT_REVIEW = ROOT / "docs" / "hints-review.md"

MAX_HINT, MAX_DO = 110, 70


def load_jsonl(path: Path) -> list[dict]:
  return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def lua_string(text: str) -> str:
  return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
  candidates = {row["id"]: row for row in load_jsonl(CANDIDATES)}
  decisions: dict[str, dict] = {}
  problems: list[str] = []
  for path in sorted(TRIAGE.glob("*.jsonl")):
    for number, decision in enumerate(load_jsonl(path), 1):
      where = f"{path.name}:{number}"
      step = decision.get("id")
      if step not in candidates:
        problems.append(f"{where}: unknown id {step!r}")
        continue
      if step in decisions:
        problems.append(f"{where}: {step} decided twice")
      kind = decision.get("decision")
      text = decision.get("text", "")
      if kind not in ("hint", "do", "skip"):
        problems.append(f"{where}: bad decision {kind!r}")
      elif kind != "skip":
        limit = MAX_HINT if kind == "hint" else MAX_DO
        if not text or len(text) > limit:
          problems.append(f"{where}: {kind} text empty or over {limit} chars")
        if not text.isascii():
          problems.append(f"{where}: non-ASCII text")
        if kind == "do" and decision.get("objective") not in candidates[step]["objectives"]:
          problems.append(f"{where}: do objective {decision.get('objective')!r} not among the quest's objectives")
      decisions[step] = decision
  missing = [step for step in candidates if step not in decisions]
  if missing:
    problems.append(f"{len(missing)} candidate rows have no decision (first: {missing[0]})")
  if problems:
    print("build: refusing to write, problems:")
    for problem in problems[:40]:
      print("  " + problem)
    return 1

  quests: dict[int, dict] = defaultdict(lambda: {"hints": [], "objectives": {}})
  for step, decision in decisions.items():
    quest = candidates[step]["quest"]
    if decision["decision"] == "hint":
      texts = [h[0] for h in quests[quest]["hints"]]
      if decision["text"] not in texts:
        quests[quest]["hints"].append((decision["text"], step))
    elif decision["decision"] == "do":
      quests[quest]["objectives"].setdefault(decision["objective"], (decision["text"], step))

  lines = [
    "-- Generated by tools/hints/build.py from tools/hints/triage/*.jsonl. Do not edit: change the",
    "-- triage decision and rebuild. Source: forever-db quest steps by the Polestar contributors,",
    "-- CC BY 4.0, reworded (see THIRD-PARTY-NOTICES); each entry names its forever-db step id.",
    "local ADDON_NAME, ns = ...",
    "",
    "ns.HintData = {",
  ]
  for quest in sorted(quests):
    entry = quests[quest]
    parts = []
    if entry["hints"]:
      hints = ", ".join(f"{{ {lua_string(text)}, {lua_string(src)} }}" for text, src in entry["hints"])
      parts.append(f"hints = {{ {hints} }}")
    if entry["objectives"]:
      objectives = ", ".join(f"[{lua_string(name)}] = {{ {lua_string(text)}, {lua_string(src)} }}"
                             for name, (text, src) in sorted(entry["objectives"].items()))
      parts.append(f"objectives = {{ {objectives} }}")
    lines.append(f"  [{quest}] = {{ {', '.join(parts)} }},")
  lines.append("}")
  OUT_LUA.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

  counts = defaultdict(int)
  for decision in decisions.values():
    counts[decision["decision"]] += 1
  review = [
    "# Hint review",
    "",
    "Generated by `tools/hints/build.py`. Every hint and do line Questmark ships, next to the forever-db",
    "text it came from. To correct one, edit its line in `tools/hints/triage/*.jsonl` and rebuild.",
    "",
    f"{counts['hint']} hints, {counts['do']} do lines, {counts['skip']} skipped, "
    f"over {len(quests)} quests.",
    "",
    "| Quest | Kind | Questmark | forever-db |",
    "| --- | --- | --- | --- |",
  ]
  for step, decision in sorted(decisions.items(), key=lambda item: (candidates[item[0]]["quest"], item[0])):
    if decision["decision"] == "skip":
      continue
    row = candidates[step]
    kind = "hint" if decision["decision"] == "hint" else f"do: {decision['objective']}"
    cell = lambda s: s.replace("|", "\\|")
    review.append(f"| {cell(row['title'])} ({row['quest']}) | {cell(kind)} | {cell(decision['text'])} | "
                  f"{cell(row['text'])} |")
  OUT_REVIEW.write_text("\n".join(review) + "\n", encoding="utf-8", newline="\n")

  print(f"build: {counts['hint']} hints, {counts['do']} do lines, {counts['skip']} skipped -> "
        f"{OUT_LUA.relative_to(ROOT).as_posix()} ({len(quests)} quests), "
        f"{OUT_REVIEW.relative_to(ROOT).as_posix()}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
